const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const ctx={};vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(__dirname,'../../web/assets/js/record-preview.js'),'utf8'),ctx);
const {format,create}=ctx.RecordPreview;
const media='A'.repeat(3000000),record={stage:'events',observations:[{preview_jpeg_base64:media}],raw_text:'长文本'.repeat(50000),events:Array.from({length:1000},(_,i)=>({description:'事件'+i}))};
const preview=format(record);
assert.ok(preview.length<25000,'DOM preview has a hard size bound');
assert.ok(preview.includes('媒体编码已省略'));
assert.ok(!preview.includes(media));
assert.equal(record.observations[0].preview_jpeg_base64,media,'original media is preserved');
assert.equal(record.events.length,1000,'original arrays remain complete for export');
assert.ok(format({image:'data:image/jpeg;base64,'+media}).includes('媒体编码已省略'));
let current=record,writes=0,reads=0,text='';
const host={get textContent(){return text;},set textContent(value){writes++;text=value;}};
const details={open:false,addEventListener(type,fn){this[type]=fn;}};
const viewer=create(details,host,()=>{reads++;return current;});
viewer.refresh();assert.equal(reads,0,'closed viewer does not traverse the record');
details.open=true;details.toggle();assert.ok(text.includes('events'));
const afterFirst=writes;details.toggle();assert.equal(writes,afterFirst,'repeated expansion reuses cached text');
details.open=false;current={stage:'gameplay',raw_text:'新结果'};viewer.refresh();
details.open=true;details.toggle();assert.ok(text.includes('新结果')&&!text.includes(media));
current=null;viewer.refresh();assert.ok(text.includes('暂无分析记录'));
const cyclic={};cyclic.self=cyclic;assert.ok(format(cyclic).includes('重复引用'));
console.log('Record preview: bounded large/media content, lazy expansion, cache, record switching and original preservation passed');
