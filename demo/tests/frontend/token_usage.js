const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const node = tag => ({tag, children: [], append(...items) {this.children.push(...items);}});
const context = {document: {createElement: node}};
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(__dirname, '../../web/assets/js/token-usage.js'), 'utf8'), context);
const {read, render} = context.TokenUsage;
assert.equal(read(null), null);
assert.equal(read({usage:{}}).input, null);
assert.equal(read({usage:{prompt_tokens:0}}).input, 0);
assert.equal(read({usage:{input_tokens:15,output_tokens:6}}).output, 6);
assert.equal(read({usage:{prompt_tokens:15,completion_tokens:6}}).total, null, 'do not invent a provider total');
assert.equal(read({usage:{total_tokens:-1,prompt_tokens:'123'}}).input, null);
assert.equal(read({usage:{totalTokenCount:9}}).total, 9);
const record = {model:'fixture', status:'failed', usage:{prompt_tokens:120,completion_tokens:30,total_tokens:150,
  prompt_tokens_details:{image_tokens:80,cached_tokens:10}, completion_tokens_details:{reasoning_tokens:20}}};
assert.equal(read(record).details.length, 3);
assert.equal(read(record).total, 150, 'subtotals must not be added again');
assert.equal(read({usage:{total_tokens:999},segments:[record,record]}).total, 300, 'never double count parent and segments');
const partial = read({usage:{total_tokens:0},segments:[record,{status:'failed'}]});
assert.equal(partial.total, null, 'missing segment usage is not zero');
assert.equal(partial.partial, true);
assert.equal(partial.known.total, 150, 'partial failures retain known provider usage');
const host = node('div');render(host, record, '失败请求');render(host, null, '尚未调用');
const text = item => [item.textContent || '', ...item.children.map(text)].join(' ');
assert.match(text(host), /输入 120 · 输出 30 · 总计 150/);
assert.match(text(host), /fixture · failed/);
assert.match(text(host), /暂无调用记录/);
assert.match(text(host), /查看原始 usage/);
const absent = node('div');render(absent,{usage:{},model_call_made:false});
assert.match(text(absent), /未返回/);assert.match(text(absent), /未调用模型/);
const failed = node('div');render(failed,{status:'failed',segments:[record,{status:'failed'}]});
assert.match(text(failed), /已返回用量小计：输入 120 · 输出 30 · 总计 150 Token/);
assert.match(text(failed), /缺失请求的用量未知，不计为 0/);
console.log('Token usage: reported counts, missing vs zero, failed calls, segments and rendering OK');
